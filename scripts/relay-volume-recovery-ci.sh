#!/usr/bin/env bash
set -euo pipefail
[[ "${RELAY_ENV:-}" == staging && "${RELAY_DISPOSABLE_WINGS_CI:-}" == 1 && "${RUNNER_ENVIRONMENT:-}" == github-hosted && "${GITHUB_EVENT_NAME:-}" == push && "${RELAY_BOOTSTRAP_SCENARIO:-}" == legacy-panel ]]
root=${RELAY_WINGS_CONTRACT_DATA:?}
uuid=${2:?}
[[ "$root" =~ ^/tmp/tmp\.[A-Za-z0-9]+/data/volumes$ && "$uuid" =~ ^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$ ]]
work=${root%/data/volumes}
archive="$work/fixture-volume.tar"
destination="$work/data/recovery-volumes"
container=relay-wings-contract
umask 077
case ${1:-} in
  backup)
    set -o noclobber
    docker exec "$container" tar --sort=name -C "$root" -cf - -- "$uuid" > "$archive"
    test -s "$archive"
    [[ $(stat -c %s "$archive") -le 1048576 ]]
    sha256sum "$archive" | cut -d ' ' -f 1
    ;;
  restore|corrupt)
    expected=${3:?}
    [[ "$expected" =~ ^[a-f0-9]{64}$ && -f "$archive" && ! -L "$archive" && -O "$archive" ]]
    input=$archive
    if [[ $1 == corrupt ]]; then
      input="$work/fixture-volume-corrupt.tar"
      (set -o noclobber; cat "$archive" > "$input"; printf 'corrupt fixture' >> "$input")
    fi
    actual=$(sha256sum "$input" | cut -d ' ' -f 1)
    if [[ "$actual" != "$expected" ]]; then
      printf 'archive digest mismatch\n' >&2
      exit 42
    fi
    [[ $1 == restore ]]
    # The archive is generated by this harness from its own fixture and authenticated
    # against the checkpoint digest before the isolated root is even created.
    docker exec "$container" mkdir -m 0755 -- "$destination"
    docker exec -i "$container" tar --numeric-owner --same-owner -C "$destination" -xf - < "$input"
    ;;
  *) exit 2 ;;
esac
